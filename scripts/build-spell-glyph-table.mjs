#!/usr/bin/env node
// Writes src/lib/battlemap/spell-glyph-table.json: the glyph every manifest
// spell wears (issue 845), as the Hand works it out with no content pack
// (namedSpellGlyph in src/lib/battlemap/hand-spells.ts). The spellbook, the
// party panel and the workshop draw a spell's glyph in the browser, and
// working it out there would ship every mechanics row to every page; the
// answers for 510 spells are a few kilobytes.
//
//   node scripts/build-spell-glyph-table.mjs           write the file
//   node scripts/build-spell-glyph-table.mjs --check   exit 1 when it is stale
import fs from "node:fs";
import path from "node:path";
import { register } from "node:module";

register("./lib/register-alias.mjs", import.meta.url);

const ROOT = path.resolve(import.meta.dirname, "..");
const out = path.join(ROOT, "src", "lib", "battlemap", "spell-glyph-table.json");

const { namedSpellGlyph } = await import("../src/lib/battlemap/hand-spells.ts");
const { SPELL_GLYPHS } = await import("../src/lib/battlemap/spell-glyph-logic.ts");

const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "src", "lib", "srd", "manifest", "spells.json"), "utf8")).spells;
const glyphs = Object.fromEntries(SPELL_GLYPHS.map((glyph) => [glyph, []]));
for (const spell of manifest) glyphs[namedSpellGlyph(spell.n)].push(spell.n);
for (const names of Object.values(glyphs)) names.sort((a, b) => a.localeCompare(b, "en"));
for (const glyph of SPELL_GLYPHS) if (!glyphs[glyph].length) delete glyphs[glyph];

const text = `${JSON.stringify(
  {
    _note:
      "GENERATED by scripts/build-spell-glyph-table.mjs: the glyph each manifest spell wears with no content pack, as namedSpellGlyph works it out. Do not edit by hand; change the mechanics rows or src/lib/battlemap/spell-glyph-names.ts and re-run the script.",
    glyphs,
  },
  null,
  2,
)}\n`;

if (process.argv.includes("--check")) {
  const now = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (now !== text) {
    console.error("src/lib/battlemap/spell-glyph-table.json is stale: run node scripts/build-spell-glyph-table.mjs");
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, text);
  console.log(`wrote ${path.relative(ROOT, out)}: ${manifest.length} spells`);
}
